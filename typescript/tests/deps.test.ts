describe("ManifestDetector — package.json fallback", () => {
  it("extracts pinned versions from dependencies", () => {
    const dir = join(TMP_DIR, "pkgjson-pinned");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package.json", JSON.stringify({
      name: "myapp",
      version: "1.0.0",
      dependencies: {
        lodash: "4.17.21",
        express: "^4.18.0",
        chalk: "~5.3.0",
      },
      devDependencies: {
        vitest: "4.1.2",
      },
    }));
    const detector = new ManifestDetector();
    const deps = detector.detect(dir)[0]!.dependencies;
    // Only pinned (starting with digit)
    expect(deps.find((d) => d.name === "lodash")?.version).toBe("4.17.21");
    expect(deps.find((d) => d.name === "vitest")?.version).toBe("4.1.2");
    // Semver ranges should be skipped
    expect(deps.find((d) => d.name === "express")).toBeUndefined();
    expect(deps.find((d) => d.name === "chalk")).toBeUndefined();
  });
});

