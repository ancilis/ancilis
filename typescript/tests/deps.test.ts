function makeConfig(mode: "audit" | "enforce" = "audit", de01Enabled = true) {
  return {
    agentName: "test-agent",
    agentOwner: "",
    mode,
    controls: new Map([["DE-01", { enabled: de01Enabled, controlId: "DE-01", controlName: "Dependency Evaluation", reason: "" }]]),
    dataClassifications: new Map(),
    activeOverlays: new Map(),
    unavailableOverlays: [],
    overlayAdjustments: [],
    evidenceRetentionDays: 30,
    humanOversightRequired: false,
    warnings: [],
    toolsAllowed: [],
    toolsBlocked: [],
    scopeMaxActionsPerMinute: null,
    scopeAllowedDestinations: [],
    scopeBlockedDestinations: [],
    activeCertifications: [],
  };
}

describe("DependencyScanner", () => {
  it("returns empty array when DE-01 is disabled", async () => {
    const scanner = new DependencyScanner(makeConfig("audit", false));
    const results = await scanner.scan(TMP_DIR);
    expect(results).toHaveLength(0);
  });

  it("returns SKIP result when no manifests found", async () => {
    const dir = join(TMP_DIR, "scan-empty");
    mkdirSync(dir, { recursive: true });
    const scanner = new DependencyScanner(makeConfig());
    const results = await scanner.scan(dir);
    expect(results).toHaveLength(1);
    expect(results[0]!.controlResults[0]!.result).toBe("SKIP");
  });

  it("returns FLAG when OSV.dev fails", async () => {
    const dir = join(TMP_DIR, "scan-oserror");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "node_modules/lodash": { version: "4.17.21" },
      },
    }));

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockRejectedValue(new Error("fetch error")) as typeof fetch;
    try {
      const scanner = new DependencyScanner(makeConfig());
      const results = await scanner.scan(dir);
      expect(results[0]!.controlResults[0]!.result).toBe("FLAG");
      expect(results[0]!.controlResults[0]!.detail).toMatch(/fetch error/i);
    } finally {
      global.fetch = origFetch;
    }
  });

  it("returns PASS when no vulnerabilities found", async () => {
    const dir = join(TMP_DIR, "scan-pass");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "node_modules/lodash": { version: "4.17.21" },
      },
    }));

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => ({ results: [{}] }),
    }) as unknown as typeof fetch;
    try {
      const scanner = new DependencyScanner(makeConfig());
      const results = await scanner.scan(dir);
      expect(results[0]!.controlResults[0]!.result).toBe("PASS");
      expect(results[0]!.decision).toBe("ALLOW");
    } finally {
      global.fetch = origFetch;
    }
  });

  it("returns FAIL and BLOCK decision for CRITICAL vulnerability", async () => {
    const dir = join(TMP_DIR, "scan-critical");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "node_modules/lodash": { version: "4.17.20" },
      },
    }));

    const osvResponse = {
      results: [
        {
          vulns: [
            {
              id: "GHSA-crit-1",
              summary: "Critical RCE",
              severity: [{ type: "CVSS_V3", score: "9.8" }],
              aliases: [],
              affected: [
                {
                  package: { name: "lodash", ecosystem: "npm" },
                  ranges: [{ events: [{ introduced: "0" }, { fixed: "4.17.21" }] }],
                },
              ],
            },
          ],
        },
      ],
    };

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => osvResponse,
    }) as unknown as typeof fetch;
    try {
      const scanner = new DependencyScanner(makeConfig());
      const results = await scanner.scan(dir);
      expect(results[0]!.decision).toBe("BLOCK");
      const cr = results[0]!.controlResults[0]!;
      expect(cr.result).toBe("FAIL");
      expect(cr.remediationHint).toMatch(/4\.17\.21/);
      expect(cr.evidenceData["package"]).toBe("lodash");
      expect(cr.evidenceData["severity"]).toBe("CRITICAL");
    } finally {
      global.fetch = origFetch;
    }
  });

  it("returns FLAG and FLAG decision for MEDIUM vulnerability", async () => {
    const dir = join(TMP_DIR, "scan-medium");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "node_modules/express": { version: "4.18.1" },
      },
    }));

    const osvResponse = {
      results: [
        {
          vulns: [
            {
              id: "GHSA-med-1",
              summary: "Open redirect",
              severity: [{ type: "CVSS_V3", score: "5.3" }],
              aliases: [],
              affected: [],
            },
          ],
        },
      ],
    };

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => osvResponse,
    }) as unknown as typeof fetch;
    try {
      const scanner = new DependencyScanner(makeConfig());
      const results = await scanner.scan(dir);
      expect(results[0]!.decision).toBe("FLAG");
      expect(results[0]!.controlResults[0]!.result).toBe("FLAG");
    } finally {
      global.fetch = origFetch;
    }
  });

  it("EvaluationResult has required fields", async () => {
    const dir = join(TMP_DIR, "scan-fields");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "node_modules/pkg": { version: "1.0.0" },
      },
    }));

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => ({ results: [{}] }),
    }) as unknown as typeof fetch;
    try {
      const scanner = new DependencyScanner(makeConfig());
      const results = await scanner.scan(dir);
      const r = results[0]!;
      expect(r.evaluationId).toBeTruthy();
      expect(r.actionId).toMatch(/^dep-scan-/);
      expect(r.timestamp).toBeTruthy();
      expect(r.agentId).toBe("cli-scan");
      expect(r.sourceType).toBe("dependency_scan");
      expect(r.mode).toBe("audit");
    } finally {
      global.fetch = origFetch;
    }
  });

  it("sorts packages worst-first in controlResults", async () => {
    const dir = join(TMP_DIR, "scan-sort");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "node_modules/aaa": { version: "1.0.0" },
        "node_modules/bbb": { version: "1.0.0" },
      },
    }));

    // aaa has MEDIUM, bbb has CRITICAL
    const osvResponse = {
      results: [
        {
          vulns: [{ id: "MED-1", summary: "Medium", severity: [{ type: "CVSS_V3", score: "5.0" }], aliases: [], affected: [] }],
        },
        {
          vulns: [{ id: "CRIT-1", summary: "Critical", severity: [{ type: "CVSS_V3", score: "9.9" }], aliases: [], affected: [] }],
        },
      ],
    };

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => osvResponse,
    }) as unknown as typeof fetch;
    try {
      const scanner = new DependencyScanner(makeConfig());
      const results = await scanner.scan(dir);
      const crs = results[0]!.controlResults;
      // bbb (CRITICAL) should appear before aaa (MEDIUM)
      expect(crs[0]!.evidenceData["package"]).toBe("bbb");
      expect(crs[1]!.evidenceData["package"]).toBe("aaa");
    } finally {
      global.fetch = origFetch;
    }
  });

  it("respects enforce mode in EvaluationResult", async () => {
    const dir = join(TMP_DIR, "scan-enforce");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: { "node_modules/pkg": { version: "1.0.0" } },
    }));

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => ({ results: [{}] }),
    }) as unknown as typeof fetch;
    try {
      const scanner = new DependencyScanner(makeConfig("enforce"));
      const results = await scanner.scan(dir);
      expect(results[0]!.mode).toBe("enforce");
    } finally {
      global.fetch = origFetch;
    }
  });
});
