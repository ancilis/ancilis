describe("OSVClient", () => {
  it("returns empty map when all deps lack versions", async () => {
    const client = new OSVClient();
    const deps: Dependency[] = [{ name: "lodash", version: null, sourceFile: "package.json" }];
    const result = await client.queryBatch(deps);
    expect(result).toEqual({});
    expect(client.lastError).toBeNull();
  });

  it("sets lastError on network failure", async () => {
    // Mock fetch to throw
    const origFetch = global.fetch;
    global.fetch = vi.fn().mockRejectedValue(new Error("network failure")) as typeof fetch;
    try {
      const client = new OSVClient();
      const deps: Dependency[] = [{ name: "lodash", version: "4.17.21", sourceFile: "p.json" }];
      const result = await client.queryBatch(deps);
      expect(result).toEqual({});
      expect(client.lastError).toMatch(/network failure/i);
    } finally {
      global.fetch = origFetch;
    }
  });

  it("sets lastError on non-OK HTTP response", async () => {
    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: false,
      status: 500,
      json: async () => ({}),
    }) as unknown as typeof fetch;
    try {
      const client = new OSVClient();
      const deps: Dependency[] = [{ name: "lodash", version: "4.17.21", sourceFile: "p.json" }];
      const result = await client.queryBatch(deps);
      expect(result).toEqual({});
      expect(client.lastError).toMatch(/500/);
    } finally {
      global.fetch = origFetch;
    }
  });

  it("maps OSV response to Vuln objects", async () => {
    const osvResponse = {
      results: [
        {
          vulns: [
            {
              id: "GHSA-xxxx-1234",
              summary: "Prototype pollution in lodash",
              severity: [{ type: "CVSS_V3", score: "9.8" }],
              aliases: ["CVE-2021-1234"],
              affected: [
                {
                  package: { name: "lodash", ecosystem: "npm" },
                  ranges: [
                    { events: [{ introduced: "0" }, { fixed: "4.17.21" }] },
                  ],
                },
              ],
            },
          ],
        },
      ],
    };

    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => osvResponse,
    }) as unknown as typeof fetch;

    try {
      const client = new OSVClient();
      const deps: Dependency[] = [{ name: "lodash", version: "4.17.20", sourceFile: "p.json" }];
      const result = await client.queryBatch(deps);

      expect(Object.keys(result)).toContain("lodash");
      const vulns = result["lodash"]!;
      expect(vulns).toHaveLength(1);
      expect(vulns[0]!.id).toBe("GHSA-xxxx-1234");
      expect(vulns[0]!.severity).toBe("CRITICAL");
      expect(vulns[0]!.fixedVersion).toBe("4.17.21");
      expect(vulns[0]!.aliases).toContain("CVE-2021-1234");
    } finally {
      global.fetch = origFetch;
    }
  });

  it("returns empty map for no vulnerabilities", async () => {
    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => ({ results: [{}] }),
    }) as unknown as typeof fetch;

    try {
      const client = new OSVClient();
      const deps: Dependency[] = [{ name: "lodash", version: "4.17.21", sourceFile: "p.json" }];
      const result = await client.queryBatch(deps);
      expect(result).toEqual({});
      expect(client.lastError).toBeNull();
    } finally {
      global.fetch = origFetch;
    }
  });

  it("maps CVSS HIGH score to HIGH severity", async () => {
    const osvResponse = {
      results: [
        {
          vulns: [
            {
              id: "GHSA-high",
              summary: "High severity issue",
              severity: [{ type: "CVSS_V3", score: "7.5" }],
              aliases: [],
              affected: [],
            },
          ],
        },
      ],
    };
    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => osvResponse,
    }) as unknown as typeof fetch;

    try {
      const client = new OSVClient();
      const deps: Dependency[] = [{ name: "pkg", version: "1.0.0", sourceFile: "p.json" }];
      const result = await client.queryBatch(deps);
      expect(result["pkg"]![0]!.severity).toBe("HIGH");
    } finally {
      global.fetch = origFetch;
    }
  });

  it("falls back to database_specific severity", async () => {
    const osvResponse = {
      results: [
        {
          vulns: [
            {
              id: "GHSA-medium",
              summary: "Medium severity issue",
              severity: [],
              database_specific: { severity: "MEDIUM" },
              aliases: [],
              affected: [],
            },
          ],
        },
      ],
    };
    const origFetch = global.fetch;
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      json: async () => osvResponse,
    }) as unknown as typeof fetch;

    try {
      const client = new OSVClient();
      const deps: Dependency[] = [{ name: "pkg", version: "1.0.0", sourceFile: "p.json" }];
      const result = await client.queryBatch(deps);
      expect(result["pkg"]![0]!.severity).toBe("MEDIUM");
    } finally {
      global.fetch = origFetch;
    }
  });
});

