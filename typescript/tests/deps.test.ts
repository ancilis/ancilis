describe("ManifestDetector — yarn.lock", () => {
  it("parses simple yarn v1 lockfile", () => {
    const dir = join(TMP_DIR, "yarn-v1");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "yarn.lock", `# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1

lodash@^4.17.0:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"
  integrity sha512-abc

express@^4.18.0:
  version "4.18.2"
  resolved "https://registry.yarnpkg.com/express/-/express-4.18.2.tgz"
`);

    const detector = new ManifestDetector();
    const manifests = detector.detect(dir);
    expect(manifests).toHaveLength(1);
    const deps = manifests[0]!.dependencies;
    expect(deps.find((d) => d.name === "lodash")?.version).toBe("4.17.21");
    expect(deps.find((d) => d.name === "express")?.version).toBe("4.18.2");
  });

  it("deduplicates multiple specifiers for same package", () => {
    const dir = join(TMP_DIR, "yarn-dedup");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "yarn.lock", `"lodash@^4.0.0", "lodash@^4.17.0":
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"
`);
    const detector = new ManifestDetector();
    const deps = detector.detect(dir)[0]!.dependencies;
    const lodashEntries = deps.filter((d) => d.name === "lodash");
    expect(lodashEntries).toHaveLength(1);
    expect(lodashEntries[0]!.version).toBe("4.17.21");
  });

  it("parses scoped packages in yarn.lock", () => {
    const dir = join(TMP_DIR, "yarn-scoped");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "yarn.lock", `"@babel/core@^7.0.0":
  version "7.22.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.22.0.tgz"
`);
    const detector = new ManifestDetector();
    const deps = detector.detect(dir)[0]!.dependencies;
    expect(deps.find((d) => d.name === "@babel/core")?.version).toBe("7.22.0");
  });
});

