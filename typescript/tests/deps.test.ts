// ManifestDetector — package-lock.json (v2)
// ---------------------------------------------------------------------------

describe("ManifestDetector — package-lock.json v2", () => {
  it("parses packages from lockfileVersion 2 format", () => {
    const dir = join(TMP_DIR, "pkglock-v2");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "": { name: "myapp", version: "1.0.0" },
        "node_modules/lodash": { version: "4.17.21" },
        "node_modules/express": { version: "4.18.2" },
        "node_modules/@babel/core": { version: "7.22.0" },
      },
    }));

    const detector = new ManifestDetector();
    const manifests = detector.detect(dir);
    expect(manifests).toHaveLength(1);
    const deps = manifests[0]!.dependencies;
    expect(deps.find((d) => d.name === "lodash")?.version).toBe("4.17.21");
    expect(deps.find((d) => d.name === "express")?.version).toBe("4.18.2");
    expect(deps.find((d) => d.name === "@babel/core")?.version).toBe("7.22.0");
    // Root entry ("") should be skipped
    expect(deps.find((d) => d.name === "")).toBeUndefined();
  });

  it("parses packages from lockfileVersion 1 format", () => {
    const dir = join(TMP_DIR, "pkglock-v1");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 1,
      dependencies: {
        lodash: { version: "4.17.21" },
        chalk: { version: "5.3.0" },
      },
    }));

    const detector = new ManifestDetector();
    const manifests = detector.detect(dir);
    const deps = manifests[0]!.dependencies;
    expect(deps).toHaveLength(2);
    expect(deps.find((d) => d.name === "lodash")?.version).toBe("4.17.21");
  });

  it("skips entries without a version field", () => {
    const dir = join(TMP_DIR, "pkglock-noversion");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", JSON.stringify({
      lockfileVersion: 2,
      packages: {
        "node_modules/lodash": { version: "4.17.21" },
        "node_modules/missing": {},
      },
    }));

    const detector = new ManifestDetector();
    const deps = detector.detect(dir)[0]!.dependencies;
    expect(deps).toHaveLength(1);
    expect(deps[0]!.name).toBe("lodash");
  });

  it("returns empty array for invalid JSON", () => {
    const dir = join(TMP_DIR, "pkglock-bad");
    mkdirSync(dir, { recursive: true });
    writeFixture(dir, "package-lock.json", "not json {");
    const detector = new ManifestDetector();
    const deps = detector.detect(dir)[0]!.dependencies;
    expect(deps).toHaveLength(0);
  });
});

